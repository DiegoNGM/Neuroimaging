"""
Validate references.bib against the project's bibliography rules.

references.bib is generated by Zotero + Better BibTeX (auto-export). The export
settings live in the maintainer's Zotero profile, outside the repository, so
this script checks the *output* to catch configuration drift:

  1. No forbidden fields (`file`, `note`): `file` leaks local paths such as
     ~/Zotero/storage/...
  2. Citation keys follow `authorYEARword` (e.g. `prince2023understanding`).
     A key without a year usually means the Zotero item has no Date.
  3. No duplicate citation keys.

Usage:
    python scripts/check_bib.py [references.bib]

Exits with status 1 if any problem is found. Standard library only, so it runs
without installing the project's dependencies (CI, pre-commit hooks).
"""

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

FORBIDDEN_FIELDS = {"file", "note"}
KEY_PATTERN = re.compile(r"^[a-z]+\d{4}[a-z]+$")
# Entry types that are not references and have no citation key.
SKIP_TYPES = {"comment", "string", "preamble"}

ENTRY_START = re.compile(r"@(\w+)\s*\{", re.ASCII)
FIELD_NAME = re.compile(r"\s*([A-Za-z][\w-]*)\s*=\s*")


def find_closing_brace(text: str, start: int) -> int:
    """Return the index of the brace that closes the one opened at `start`."""
    depth = 0
    for i in range(start, len(text)):
        char = text[i]
        escaped = i > 0 and text[i - 1] == "\\"  # \{ and \} are literal braces
        if char == "{" and not escaped:
            depth += 1
        elif char == "}" and not escaped:
            depth -= 1
            if depth == 0:
                return i
    raise ValueError(f"unbalanced braces in entry starting at offset {start}")


def skip_value(body: str, pos: int) -> int:
    """Return the position right after a field value that starts at `pos`."""
    while pos < len(body):
        char = body[pos]
        if char == "{":
            pos = find_closing_brace(body, pos) + 1
        elif char == '"':
            end = body.find('"', pos + 1)
            pos = len(body) if end == -1 else end + 1
        elif char == ",":
            return pos + 1
        else:
            pos += 1
    return pos


def parse_fields(body: str) -> list[str]:
    """Return the top-level field names of an entry body (after the key)."""
    fields = []
    pos = 0
    while True:
        match = FIELD_NAME.match(body, pos)
        if not match:
            break
        fields.append(match.group(1).lower())
        pos = skip_value(body, match.end())
    return fields


def parse_entries(text: str) -> list[tuple[str, str, list[str], int]]:
    """Return (entry_type, key, field_names, line_number) for each reference."""
    entries = []
    pos = 0
    while match := ENTRY_START.search(text, pos):
        entry_type = match.group(1).lower()
        open_brace = match.end() - 1
        close_brace = find_closing_brace(text, open_brace)
        pos = close_brace + 1
        if entry_type in SKIP_TYPES:
            continue
        content = text[open_brace + 1 : close_brace]
        key, _, body = content.partition(",")
        line = text.count("\n", 0, match.start()) + 1
        entries.append((entry_type, key.strip(), parse_fields(body), line))
    return entries


def check(path: Path) -> list[str]:
    """Return a list of human-readable problems found in `path`."""
    entries = parse_entries(path.read_text(encoding="utf-8"))
    problems = []

    for _, key, fields, line in entries:
        where = f"{path}:{line} [{key}]"
        for field in sorted(FORBIDDEN_FIELDS.intersection(fields)):
            problems.append(
                f"{where}: forbidden field '{field}' "
                "(check 'Fields to omit from export' in Better BibTeX)"
            )
        if not KEY_PATTERN.match(key):
            problems.append(
                f"{where}: key does not match authorYEARword "
                "(missing Date or author in Zotero? refresh the citation key)"
            )

    counts = Counter(key for _, key, _, _ in entries)
    for key, count in counts.items():
        if count > 1:
            problems.append(f"{path}: duplicate key '{key}' ({count} entries)")

    return problems


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "bib",
        nargs="?",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "references.bib",
        help="Path to the .bib file (default: <project root>/references.bib)",
    )
    args = parser.parse_args()

    if not args.bib.is_file():
        sys.exit(f"error: {args.bib} not found")

    problems = check(args.bib)
    for problem in problems:
        print(problem, file=sys.stderr)

    if problems:
        sys.exit(f"\n{len(problems)} problem(s) found in {args.bib}")
    print(f"{args.bib}: OK")


if __name__ == "__main__":
    main()
